#!/usr/bin/env python3
"""Rebuild the checked-in office / aerial-course SDF assets, using only stdlib.

Geometry uses metres. Collision geometry follows furniture structure (no filled
bounding boxes over doors or under tables). Decorative pieces are visual only.
"""
from pathlib import Path
import math
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / 'examples/wheel_car_4w/litesim_models'


def sub(parent, tag, text=None, **attrs):
    item = ET.SubElement(parent, tag, attrs)
    if text is not None:
        item.text = str(text)
    return item


def numbers(values):
    return ' '.join(f'{x:.8g}' for x in values)


def document(name, static=True):
    root = ET.Element('sdf', version='1.9')
    model = sub(root, 'model', name=name)
    sub(model, 'static', str(static).lower())
    return root, model, sub(model, 'link', name='base_link' if not static else 'structure')


def solid(link, name, xyz, size, color, *, kind='box', rpy=(0, 0, 0), collision=True):
    for role in ('visual', 'collision') if collision else ('visual',):
        item = sub(link, role, name=name)
        sub(item, 'pose', numbers((*xyz, *rpy)))
        shape = sub(sub(item, 'geometry'), kind)
        if kind == 'box':
            sub(shape, 'size', numbers(size))
        elif kind == 'cylinder':
            sub(shape, 'radius', size[0]); sub(shape, 'length', size[1])
        else:
            sub(shape, 'radius', size[0])
        if role == 'visual':
            mat = sub(item, 'material')
            for channel in ('ambient', 'diffuse'):
                sub(mat, channel, numbers((*color, 1)))
            metal = sub(sub(mat, 'pbr'), 'metal')
            sub(metal, 'roughness', '.72'); sub(metal, 'metalness', '0')


def save(root, path):
    path.parent.mkdir(parents=True, exist_ok=True)
    ET.indent(root, space='  ')
    path.write_text('<?xml version="1.0"?>\n<!-- Generated by scripts/fixtures/generate_example_worlds.py -->\n' +
                    ET.tostring(root, encoding='unicode') + '\n')


def save_model(root, name):
    save(root, ASSETS / 'models' / name / 'model.sdf')
    config = ET.Element('model')
    sub(config, 'name', name); sub(config, 'version', '1.0')
    sub(config, 'sdf', 'model.sdf', version='1.9')
    sub(config, 'description', 'LiteSim3D procedural example geometry; metres.')
    save(config, ASSETS / 'models' / name / 'model.config')


WALL = (.78, .82, .86)
WOOD = (.64, .43, .24)
DARK = (.10, .14, .19)
BLUE = (.12, .37, .55)
GREEN = (.22, .46, .27)


def office():
    root, _, link = document('office_layout')
    def box(name, xyz, size, color=WALL, **kw):
        solid(link, name, xyz, size, color, **kw)
    # 28 x 22 m office. No roof, so the read-only orbit view can inspect rooms.
    box('north_wall', (4, 11, 1.5), (28, .2, 3))
    box('south_wall', (4, -11, 1.5), (28, .2, 3))
    for x in (-10, 18): box(f'end_{x}', (x, 0, 1.5), (.2, 22, 3))
    # A 3.6 m corridor, door openings at x = -5, 3 and 11.
    for y in (-1.9, 1.9):
        for x, width in ((-8, 4), (-1, 6), (7, 6), (15, 6)):
            box(f'corridor_{y}_{x}', (x, y, 1.4), (width, .16, 2.8))
        for x in (-5, 3, 11):
            box(f'lintel_{y}_{x}', (x, y, 2.6), (2, .16, .4), BLUE)
    for x in (-1, 7):
        box(f'south_room_{x}', (x, -6.5, 1.4), (.16, 9, 2.8))
    box('north_meeting_divider', (10, 6.5, 1.4), (.16, 9, 2.8))
    # Low partitions keep the work area readable and create rich LiDAR returns.
    for x in (-5, 1, 6): box(f'partition_{x}', (x, 7.4, .65), (3.8, .12, 1.3), BLUE)
    def desk(name, x, y, width=1.7, depth=.85):
        box(name+'_top', (x, y, .76), (width, depth, .08), WOOD)
        for dx in (-width/2+.1, width/2-.1):
            for dy in (-depth/2+.08, depth/2-.08):
                box(f'{name}_leg_{dx}_{dy}', (x+dx, y+dy, .36), (.07, .07, .72), DARK)
        box(name+'_screen', (x+.12, y+.13, 1.12), (.58, .05, .35), DARK, collision=False)
        box(name+'_display', (x+.12, y+.10, 1.12), (.50, .015, .28), (.18,.45,.65), collision=False)
        box(name+'_stand', (x+.12, y+.13, .88), (.07,.08,.2), DARK, collision=False)
    def chair(name, x, y):
        box(name+'_seat', (x,y,.48), (.48,.5,.10), BLUE)
        box(name+'_back', (x,y-.23,.77), (.48,.07,.58), BLUE)
        solid(link, name+'_pedestal', (x,y,.23), (.08,.46), DARK, kind='cylinder')
        box(name+'_foot', (x,y,.05), (.52,.52,.07), DARK)
    for i, (x,y) in enumerate(((-7,5),(-3,5),(1,5),(6,5),(-7,9),(-3,9),(1,9),(6,9))):
        desk(f'desk_{i}', x,y); chair(f'chair_{i}',x,y-1)
    # Meeting room, reception, lounge and server room.
    box('meeting_top', (3,-6.6,.78), (3.5,1.4,.12), WOOD)
    for x in (1.7,4.3): box(f'meeting_base_{x}', (x,-6.6,.36), (.3,.8,.72), DARK)
    for i,x in enumerate((1.7,3,4.3)):
        chair(f'meeting_chair_{i}', x,-8)
        chair(f'meeting_chair_n_{i}', x,-5.2)
    box('whiteboard', (6.85,-7,1.65), (.07,2.8,1.2), (.92,.94,.92), collision=False)
    box('reception', (-6,-4,.6), (4,.8,1.2), WOOD)
    for i,(x,y) in enumerate(((-7,-8),(-3,-8))):
        box(f'sofa_{i}_base',(x,y,.38),(2.4,.85,.6),BLUE)
        box(f'sofa_{i}_back',(x,y+.4,.75),(2.4,.18,1.15),BLUE)
    box('coffee_table',(-5,-6.4,.3),(1.3,.8,.6),WOOD)
    for i in range(4):
        x=11+i*1.6
        box(f'server_{i}',(x,-8,1.1),(.85,1.3,2.2),DARK)
        for z in (.3,.7,1.1,1.5,1.9):
            box(f'server_{i}_panel_{z}',(x,-7.34,z),(.65,.02,.1),BLUE,collision=False)
    for i,(x,y) in enumerate(((16,8),(12,8),(-8,2.8),(16,-3))):
        solid(link,f'pot_{i}',(x,y,.22),(.24,.44),WOOD,kind='cylinder')
        solid(link,f'plant_{i}',(x,y,.75),(.40,),GREEN,kind='sphere',collision=False)
    box('corridor_guide', (4,0,.008), (27,.12,.012), (.20,.52,.58), collision=False)
    save_model(root,'office_layout')


def arena():
    root, _, link = document('aerial_course')
    def box(name, xyz, size, color=BLUE, **kw):
        solid(link,name,xyz,size,color,**kw)
    for x in (-12,12): box(f'wall_x{x}',(x,0,2),(.25,24,4),WALL)
    for y in (-12,12): box(f'wall_y{y}',(0,y,2),(24,.25,4),WALL)
    for i,(x,y,h) in enumerate(((-8,3,3),(-3,5,5),(3,6,6),(8,3,4),(8,-7,2),(-2,-8,3.5))):
        solid(link,f'tower_{i}',(x,y,h/2),(.48,h),(.63,.67,.71),kind='cylinder')
    # Three real open gates at different heights; each opening is 3 x 2 m.
    for i,(x,y,z) in enumerate(((-3,-5,2),(3,-1,3.5),(6,6,5.5))):
        for dy in (-1.65,1.65): box(f'gate_{i}_side{dy}',(x,y+dy,z),(.28,.3,2.6))
        for dz in (-1.15,1.15): box(f'gate_{i}_bar{dz}',(x,y,z+dz),(.28,3.6,.3))
        for dy in (-1.65,1.65):
            box(f'gate_{i}_support{dy}',(x,y+dy,(z-1.3)/2),(.15,.15,z-1.3),DARK)
    for i in range(4):
        box(f'step_platform_{i}',(6,-5+i*1.5,(i+1)*.35),(3,1.35,(i+1)*.7),(.55,.43,.31))
    # Overhangs and bridge leave navigable volumes both above and below.
    box('bridge',(0,6,3.3),(9,1.8,.25),(.72,.48,.18))
    for x in (-4,4): box(f'bridge_support{x}',(x,6,1.6),(.3,.3,3.2),DARK)
    box('overhead_beam',(-5,0,5.4),(10,.45,.45),(.75,.51,.2))
    for x in (-9.5,-.5): box(f'beam_pillar{x}',(x,0,2.7),(.35,.35,5.4),DARK)
    for i,(x,y) in enumerate(((-8,8),(-5,9),(8,9),(9,-1))):
        for z in (.5,1.5,2.5): box(f'rack_{i}_shelf{z}',(x,y,z),(2,1,.12),WOOD)
        for dx in (-.95,.95): box(f'rack_{i}_post{dx}',(x+dx,y,1.5),(.1,1,3),DARK)
    # Distinct ground markings help RGB and depth inspection without collisions.
    for x in range(-10,12,2): box(f'grid_x{x}',(x,0,.006),(.025,23,.01),(.50,.57,.62),collision=False)
    for y in range(-10,12,2): box(f'grid_y{y}',(0,y,.006),(23,.025,.01),(.50,.57,.62),collision=False)
    box('landing_pad',(-8,-8,.015),(2.4,2.4,.02),(.16,.49,.51),collision=False)
    for x in (-8.45,-7.55): box(f'pad_h{x}',(x,-8,.03),(.12,1.2,.01),(.92,.94,.89),collision=False)
    box('pad_cross',(-8,-8,.03),(1,.12,.01),(.92,.94,.89),collision=False)
    save_model(root,'aerial_course')


def drone():
    root, model, link = document('quadrotor',False)
    solid(link,'body',(0,0,0),(.42,.28,.16),BLUE)
    solid(link,'battery',(0,0,.12),(.26,.18,.1),DARK,collision=False)
    for x in (-.32,.32):
        for y in (-.32,.32):
            name=f'motor_{x}_{y}'
            angle=math.atan2(y,x)
            solid(link,name+'_arm',(x/2,y/2,0),(.46,.06,.055),DARK,rpy=(0,0,angle))
            solid(link,name,(x,y,.055),(.06,.12),DARK,kind='cylinder')
            # Propeller safety envelope is represented by the actual disk volume.
            solid(link,name+'_rotor',(x,y,.13),(.18,.018),(.25,.29,.32),kind='cylinder')
    for y in (-.2,.2):
        solid(link,f'skid{y}',(0,y,-.22),(.52,.035,.035),DARK)
        for x in (-.18,.18): solid(link,f'leg{x}_{y}',(x,y,-.13),(.03,.03,.18),DARK)
    for name,xyz,rpy in (('lidar_link',(0,0,.25),(0,0,0)),('imu_link',(0,0,0),(0,0,0)),
                         ('camera_optical_frame',(.25,0,-.03),(-math.pi/2,0,-math.pi/2))):
        mount=sub(model,'link',name=name)
        sub(mount,'pose',numbers((*xyz,*rpy)),relative_to='base_link')
        if name=='lidar_link': solid(mount,'lidar',(0,0,0),(.07,.08),(.85,.84,.77),kind='cylinder')
        if name=='camera_optical_frame': solid(mount,'camera',(0,0,0),(.1,.08,.06),DARK)
        joint=sub(model,'joint',name=name+'_joint',type='fixed')
        sub(joint,'parent','base_link');sub(joint,'child',name)
    save_model(root,'quadrotor')


def world(name, robot, layout, floor_size, robot_pose, view):
    root=ET.Element('sdf',version='1.9');w=sub(root,'world',name=name)
    physics=sub(w,'physics',name='litesim_timing',type='ignored',default='true')
    sub(physics,'max_step_size','.005');sub(physics,'real_time_factor','1')
    scene=sub(w,'scene');sub(scene,'ambient','.48 .48 .48 1');sub(scene,'background','.11 .15 .20 1')
    light=sub(w,'light',name='sun',type='directional');sub(light,'direction','-.4 -.6 -1')
    sub(light,'diffuse','.95 .95 .95 1');sub(light,'cast_shadows','true')
    camera=sub(sub(w,'gui'),'camera',name='overview');sub(camera,'pose',numbers(view))
    for asset,where in ((robot,robot_pose),(layout,(0,0,0,0,0,0))):
        include=sub(w,'include');sub(include,'uri','model://'+asset);sub(include,'pose',numbers(where))
    ground=sub(w,'model',name='ground');sub(ground,'static','true');g=sub(ground,'link',name='slab')
    solid(g,'floor',(4 if name=='office' else 0,0,-.15),(*floor_size,.3),(.64,.68,.71))
    # Mesh/MTL texture resource is also exercised by both larger scenes.
    include=sub(w,'include');sub(include,'uri','model://textured_crate')
    sub(include,'pose','15 5 .5 0 0 .3' if name=='office' else '8 -10 .5 0 0 .3')
    save(root,ASSETS/'worlds'/f'{name}.sdf')


